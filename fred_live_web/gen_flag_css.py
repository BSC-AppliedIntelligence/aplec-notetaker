"""Regenerate static/flags.css from languages.py.

Usage: python -m fred_live_web.gen_flag_css > fred_live_web/static/flags.css

Emits a base `.flag` class plus one `background-image` rule per referenced
flag-icons code. Run after editing LANGUAGES (and download any new SVGs into
static/flags/4x3/ — `python -m fred_live_web.languages` reports which are
missing).
"""
from __future__ import annotations

from .languages import flag_codes

HEADER = """/* Generated by `python -m fred_live_web.gen_flag_css`. Do not edit by hand.
   Flag EMOJI don't render on Windows (Segoe UI Emoji omits flags), so we serve
   vendored flag-icons SVGs instead. */

.flag {
  display: inline-block; width: 1.33em; height: 1em;
  background-size: contain; background-position: center; background-repeat: no-repeat;
  border-radius: 2.5px; vertical-align: -0.15em;
  box-shadow: 0 0 0 1px rgb(0 0 0 / .18) inset;
}
.flag-inline { width: 1.4em; height: 1.05em; vertical-align: -0.18em; margin-right: 5px; }
"""


def render() -> str:
    lines = [HEADER]
    for code in sorted(flag_codes()):
        lines.append(f'.flag-{code} {{ background-image: url("/static/flags/4x3/{code}.svg"); }}')
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    print(render(), end="")
